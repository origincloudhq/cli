//! Generates the `origin pvs` commands from the API definitions
//! (origincloudhq/api):
//!
//! ```text
//! origincloud-cli-generator <api-dir> <out-dir>
//! ```
//!
//! `<api-dir>` is a checkout of the API; its dependencies are downloaded at
//! the commits its `buf.lock` pins. Two files are written to `<out-dir>`, at
//! their paths in this repository, under `crates/cli/src/pvs/generated/`:
//!
//! - `commands.rs`: a clap subcommand per method of every service of the
//!   newest `origincloud.pvs.{version}` package, its flags taken from the
//!   method's request message, and the code that builds the request and
//!   calls the Rust SDK's client for it;
//! - `pvs.binpb`: that package's descriptors, which the coverage test reads
//!   to check that every method has a command.
//!
//! A method the generator can't make a command for, such as one with a
//! field of a type it doesn't support, is reported on standard error and
//! left out; the coverage test then fails until the generator supports it.
//!
//! The output depends on nothing but the API checkout, the pinned
//! dependencies and the versions `Cargo.lock` pins, so generating from an
//! unchanged API changes nothing.

mod commands;
mod deps;
mod docs;
mod policy;

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use anyhow::{bail, ensure, Context, Result};
use prost_reflect::DescriptorPool;
use prost_types::FileDescriptorSet;
use protox::file::{
    ChainFileResolver, File, FileResolver, GoogleFileResolver, IncludeFileResolver,
};

const HEADER: &str = "// Code generated by origincloud-cli-generator. DO NOT EDIT.\n";

/// The service whose commands are generated, as its packages name it.
const SERVICE: &str = "pvs";

/// Where the generated files go, in the repository.
const OUT_DIR: &str = "crates/cli/src/pvs/generated";

fn main() -> Result<()> {
    let args: Vec<PathBuf> = std::env::args_os().skip(1).map(PathBuf::from).collect();
    let [api, out] = args.as_slice() else {
        bail!("usage: origincloud-cli-generator <api-dir> <out-dir>");
    };

    let dependencies = deps::fetch(api)?;
    let (pool, fds) = compile(api, dependencies)?;
    let package = newest_package(&pool, SERVICE)?;
    let comments = docs::Comments::new(&fds, &package);
    let policy =
        policy::Policy::load(&Path::new(env!("CARGO_MANIFEST_DIR")).join("commands.toml"))?;
    for (method, field) in policy.entries() {
        if !names_a_field(&pool, &package, method, field) {
            eprintln!("warning: commands.toml names {method} {field}, which the API doesn't have");
        }
    }

    let generated = commands::generate(&pool, &comments, &policy, &package)?;
    for skipped in &generated.skipped {
        eprintln!("warning: no command for {skipped}");
    }

    let mut files: BTreeMap<PathBuf, Vec<u8>> = BTreeMap::new();
    files.insert(
        Path::new(OUT_DIR).join("commands.rs"),
        format!(
            "{HEADER}// source: origincloudhq/api, package {package}\n\n{}",
            generated.code
        )
        .into_bytes(),
    );
    files.insert(
        Path::new(OUT_DIR).join("pvs.binpb"),
        descriptor(&pool, &package),
    );
    for (path, content) in &files {
        let path = out.join(path);
        std::fs::create_dir_all(path.parent().context("a file has a directory")?)?;
        std::fs::write(&path, content).with_context(|| format!("writing {}", path.display()))?;
    }
    Ok(())
}

/// Compiles every file under the API's `origincloud/`, with source info
/// and the files they import.
fn compile(
    api: &Path,
    dependencies: BTreeMap<String, String>,
) -> Result<(DescriptorPool, FileDescriptorSet)> {
    let mut resolver = ChainFileResolver::new();
    resolver.add(IncludeFileResolver::new(api.to_owned()));
    resolver.add(MemoryResolver(dependencies));
    resolver.add(GoogleFileResolver::new());
    let mut compiler = protox::Compiler::with_file_resolver(resolver);
    compiler.include_imports(true).include_source_info(true);

    let mut names = Vec::new();
    collect_protos(api, &api.join("origincloud"), &mut names)?;
    names.sort();
    ensure!(
        !names.is_empty(),
        "no .proto files under {}",
        api.join("origincloud").display()
    );
    compiler
        .open_files(&names)
        .map_err(|e| anyhow::anyhow!("{e:?}"))?;
    Ok((compiler.descriptor_pool(), compiler.file_descriptor_set()))
}

fn collect_protos(root: &Path, dir: &Path, names: &mut Vec<String>) -> Result<()> {
    for entry in std::fs::read_dir(dir).with_context(|| format!("reading {}", dir.display()))? {
        let path = entry?.path();
        if path.is_dir() {
            collect_protos(root, &path, names)?;
        } else if path.extension().is_some_and(|e| e == "proto") {
            let relative = path.strip_prefix(root)?;
            let name: Vec<String> = relative
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect();
            names.push(name.join("/"));
        }
    }
    Ok(())
}

/// The downloaded dependencies, by import path.
struct MemoryResolver(BTreeMap<String, String>);

impl FileResolver for MemoryResolver {
    fn open_file(&self, name: &str) -> Result<File, protox::Error> {
        match self.0.get(name) {
            Some(source) => File::from_source(name, source),
            None => Err(protox::Error::file_not_found(name)),
        }
    }
}

/// The newest version of `origincloud.{service}`: a stable version before
/// a beta, a beta before an alpha, and a higher number first.
fn newest_package(pool: &DescriptorPool, service: &str) -> Result<String> {
    let prefix = format!("origincloud.{service}.");
    let mut versions: Vec<(VersionKey, String)> = Vec::new();
    for file in pool.files() {
        let package = file.package_name();
        if let Some(version) = package.strip_prefix(&prefix) {
            let key = version_key(version)
                .with_context(|| format!("the package {package} has no version"))?;
            if !versions.iter().any(|(_, p)| p == package) {
                versions.push((key, package.to_owned()));
            }
        }
    }
    versions.sort();
    versions
        .pop()
        .map(|(_, package)| package)
        .with_context(|| format!("the API has no origincloud.{service} package"))
}

/// Orders versions: (major, stability, minor), stability 0 for alpha, 1 for
/// beta and 2 for stable.
type VersionKey = (u32, u8, u32);

fn version_key(version: &str) -> Option<VersionKey> {
    let rest = version.strip_prefix('v')?;
    let digits = rest.bytes().take_while(u8::is_ascii_digit).count();
    let major = rest[..digits].parse().ok()?;
    let rest = &rest[digits..];
    let (stability, minor) = if rest.is_empty() {
        (2, 0)
    } else if let Some(n) = rest.strip_prefix("beta") {
        (1, n.parse().ok()?)
    } else {
        (0, rest.strip_prefix("alpha")?.parse().ok()?)
    };
    Some((major, stability, minor))
}

/// Whether `method` of `package` has the field `field`, a path from its
/// request such as `volume.size_gib`.
fn names_a_field(pool: &DescriptorPool, package: &str, method: &str, field: &str) -> bool {
    let Some(method) = pool
        .services()
        .filter(|s| s.package_name() == package)
        .flat_map(|s| s.methods().collect::<Vec<_>>())
        .find(|m| m.name() == method)
    else {
        return false;
    };
    let mut message = method.input();
    let mut parts = field.split('.').peekable();
    while let Some(part) = parts.next() {
        let Some(f) = message.get_field_by_name(part) else {
            return false;
        };
        if parts.peek().is_some() {
            match f.kind() {
                prost_reflect::Kind::Message(m) => message = m,
                _ => return false,
            }
        }
    }
    true
}

/// The files of `package` and every file they import, without source info:
/// what the tests need to list the package's services and methods, and to
/// read their annotations. They are encoded from the pool, which keeps the
/// options' extensions (`google.api.resource` and the like) that
/// `prost_types` drops.
fn descriptor(pool: &DescriptorPool, package: &str) -> Vec<u8> {
    let mut wanted: Vec<String> = pool
        .files()
        .filter(|f| f.package_name() == package)
        .map(|f| f.name().to_owned())
        .collect();
    let mut kept = std::collections::BTreeSet::new();
    while let Some(name) = wanted.pop() {
        if let Some(file) = pool.get_file_by_name(&name) {
            if kept.insert(name) {
                wanted.extend(file.dependencies().map(|d| d.name().to_owned()));
            }
        }
    }
    // Each file after those it imports, in a fixed order.
    let mut out = Vec::new();
    let mut placed = std::collections::BTreeSet::new();
    while placed.len() < kept.len() {
        for name in &kept {
            let file = pool.get_file_by_name(name).expect("a kept file");
            if !placed.contains(name) && file.dependencies().all(|d| placed.contains(d.name())) {
                let encoded = without_field(&file.encode_to_vec(), SOURCE_CODE_INFO);
                // FileDescriptorSet.file, field 1, length-delimited.
                out.push(0x0a);
                prost::encoding::encode_varint(encoded.len() as u64, &mut out);
                out.extend_from_slice(&encoded);
                placed.insert(name.clone());
            }
        }
    }
    out
}

/// `FileDescriptorProto.source_code_info`.
const SOURCE_CODE_INFO: u64 = 9;

/// The encoded message `message` without its field number `field`.
fn without_field(message: &[u8], field: u64) -> Vec<u8> {
    let mut out = Vec::with_capacity(message.len());
    let mut rest = message;
    while !rest.is_empty() {
        let start = rest;
        let key = prost::encoding::decode_varint(&mut rest).expect("a valid descriptor");
        let skip = match key & 7 {
            0 => {
                prost::encoding::decode_varint(&mut rest).expect("a valid descriptor");
                0
            }
            1 => 8,
            2 => prost::encoding::decode_varint(&mut rest).expect("a valid descriptor") as usize,
            5 => 4,
            other => panic!("wire type {other} in a descriptor"),
        };
        rest = &rest[skip..];
        if key >> 3 != field {
            out.extend_from_slice(&start[..start.len() - rest.len()]);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn versions_order_stable_before_beta_before_alpha() {
        let mut keys = ["v1beta1", "v1", "v1alpha2", "v2beta1", "v1beta2"]
            .map(|v| (version_key(v).unwrap(), v));
        keys.sort();
        let order: Vec<&str> = keys.iter().map(|(_, v)| *v).collect();
        assert_eq!(order, ["v1alpha2", "v1beta1", "v1beta2", "v1", "v2beta1"]);
        assert!(version_key("latest").is_none());
    }
}
