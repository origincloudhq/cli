//! Generates the command groups of the `origin` CLI from the API
//! definitions (origincloudhq/api), one per service:
//!
//! ```text
//! origincloud-cli-generator <api-dir> <sdk-dir> <out-dir>
//! ```
//!
//! `<api-dir>` is a checkout of the API; its dependencies are downloaded at
//! the commits its `buf.lock` pins. `<sdk-dir>` is a checkout of the Rust
//! SDK generated from it, whose clients say which services answer at a
//! region's host (`client.service("pvs", true)`) and which only at their
//! regionless one. The files are written to `<out-dir>`, at
//! their paths in this repository, under `crates/cli/src/sdk/generated/`:
//!
//! - `{service}.rs` for each service, such as `pvs.rs` for the packages
//!   `origincloud.pvs.*`: a clap subcommand per method of every service of
//!   its newest package, its flags taken from the method's request message,
//!   and the code that builds the request and calls the Rust SDK's client
//!   for it. A package whose methods answer with long-running operations
//!   also gets a command per method of the newest `origincloud.longrunning`
//!   package, sent to that service's host, which serves its operations;
//! - `services.rs`: the groups, `origin {service}`, each with its
//!   `--endpoint`, and the code running a command of one;
//! - `api.binpb`: the descriptors of those packages, which the coverage
//!   test reads to check that every method has a command.
//!
//! A method the generator can't make a command for, such as one with a
//! field of a type it doesn't support, is reported on standard error and
//! left out; the coverage test then fails until the generator supports it,
//! or `commands.toml` leaves it out with a reason.
//!
//! The output depends on nothing but the API checkout, the pinned
//! dependencies and the versions `Cargo.lock` pins, so generating from an
//! unchanged API changes nothing.

mod commands;
mod deps;
mod docs;
mod policy;

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use anyhow::{bail, ensure, Context, Result};
use prost_reflect::DescriptorPool;
use prost_types::FileDescriptorSet;
use protox::file::{
    ChainFileResolver, File, FileResolver, GoogleFileResolver, IncludeFileResolver,
};

use commands::OPERATIONS;

const HEADER: &str = "// Code generated by origincloud-cli-generator. DO NOT EDIT.\n";

/// Where the generated files go, in the repository.
const OUT_DIR: &str = "crates/cli/src/sdk/generated";

fn main() -> Result<()> {
    let args: Vec<PathBuf> = std::env::args_os().skip(1).map(PathBuf::from).collect();
    let [api, sdk, out] = args.as_slice() else {
        bail!("usage: origincloud-cli-generator <api-dir> <sdk-dir> <out-dir>");
    };

    let dependencies = deps::fetch(api)?;
    let (pool, fds) = compile(api, dependencies)?;
    let services = services(&pool)?;
    ensure!(!services.is_empty(), "the API has no origincloud service");
    let regional = regional_services(sdk)?;
    let operations = newest_package(&pool, OPERATIONS).ok();
    let comments = docs::Comments::new(&fds);
    let policy =
        policy::Policy::load(&Path::new(env!("CARGO_MANIFEST_DIR")).join("commands.toml"))?;

    let mut packages: BTreeMap<&str, &str> = services
        .iter()
        .map(|(s, p)| (s.as_str(), p.as_str()))
        .collect();
    if let Some(operations) = &operations {
        packages.insert(OPERATIONS, operations);
    }
    for (service, method, field) in policy.entries() {
        let named = packages
            .get(service)
            .is_some_and(|package| names_a_field(&pool, package, method, field));
        if !named {
            eprintln!(
                "warning: commands.toml names {service} {method} {field}, which the API doesn't have"
            );
        }
    }
    for group in &policy.service {
        if !services.contains_key(&group.name) {
            eprintln!(
                "warning: commands.toml describes the service {}, which the API doesn't have",
                group.name
            );
        }
    }

    let mut files: BTreeMap<PathBuf, Vec<u8>> = BTreeMap::new();
    let mut groups = Vec::new();
    for (service, package) in &services {
        let generated =
            commands::generate(&pool, &comments, &policy, package, operations.as_deref())?;
        for skipped in &generated.skipped {
            eprintln!("warning: no command for {skipped}");
        }
        let mut source = format!("// source: origincloudhq/api, package {package}");
        if generated.operations {
            if let Some(operations) = &operations {
                source.push_str(&format!(", and {operations} at its host"));
            }
        }
        files.insert(
            Path::new(OUT_DIR).join(format!("{service}.rs")),
            format!("{HEADER}{source}\n\n{}", generated.code).into_bytes(),
        );
        let regional = *regional.get(service).with_context(|| {
            format!(
                "the SDK at {} has no client of the service {service}: it must be generated from the same API revision",
                sdk.display()
            )
        })?;
        groups.push(commands::group(
            &pool,
            &comments,
            &policy,
            package,
            regional,
            generated.lists_zones,
        ));
    }
    files.insert(
        Path::new(OUT_DIR).join("services.rs"),
        format!(
            "{HEADER}// source: origincloudhq/api\n\n{}",
            commands::services(&groups)?
        )
        .into_bytes(),
    );
    let described: Vec<&str> = packages.values().copied().collect();
    files.insert(
        Path::new(OUT_DIR).join("api.binpb"),
        descriptor(&pool, &described),
    );
    for (path, content) in &files {
        let path = out.join(path);
        std::fs::create_dir_all(path.parent().context("a file has a directory")?)?;
        std::fs::write(&path, content).with_context(|| format!("writing {}", path.display()))?;
    }
    Ok(())
}

/// Compiles every file under the API's `origincloud/`, with source info
/// and the files they import.
fn compile(
    api: &Path,
    dependencies: BTreeMap<String, String>,
) -> Result<(DescriptorPool, FileDescriptorSet)> {
    let mut resolver = ChainFileResolver::new();
    resolver.add(IncludeFileResolver::new(api.to_owned()));
    resolver.add(MemoryResolver(dependencies));
    resolver.add(GoogleFileResolver::new());
    let mut compiler = protox::Compiler::with_file_resolver(resolver);
    compiler.include_imports(true).include_source_info(true);

    let mut names = Vec::new();
    collect_protos(api, &api.join("origincloud"), &mut names)?;
    names.sort();
    ensure!(
        !names.is_empty(),
        "no .proto files under {}",
        api.join("origincloud").display()
    );
    compiler
        .open_files(&names)
        .map_err(|e| anyhow::anyhow!("{e:?}"))?;
    Ok((compiler.descriptor_pool(), compiler.file_descriptor_set()))
}

fn collect_protos(root: &Path, dir: &Path, names: &mut Vec<String>) -> Result<()> {
    for entry in std::fs::read_dir(dir).with_context(|| format!("reading {}", dir.display()))? {
        let path = entry?.path();
        if path.is_dir() {
            collect_protos(root, &path, names)?;
        } else if path.extension().is_some_and(|e| e == "proto") {
            let relative = path.strip_prefix(root)?;
            let name: Vec<String> = relative
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect();
            names.push(name.join("/"));
        }
    }
    Ok(())
}

/// The downloaded dependencies, by import path.
struct MemoryResolver(BTreeMap<String, String>);

impl FileResolver for MemoryResolver {
    fn open_file(&self, name: &str) -> Result<File, protox::Error> {
        match self.0.get(name) {
            Some(source) => File::from_source(name, source),
            None => Err(protox::Error::file_not_found(name)),
        }
    }
}

/// The newest package of every service of the API but the operations
/// one, by service: `pvs` is `origincloud.pvs.v1beta1`. Every file under
/// `origincloud/` must be in a package `origincloud.{service}.{version}`:
/// any other shape fails generation, rather than leaving its methods out
/// unnoticed.
fn services(pool: &DescriptorPool) -> Result<BTreeMap<String, String>> {
    let mut names: Vec<String> = Vec::new();
    for file in pool
        .files()
        .filter(|f| f.name().starts_with("origincloud/"))
    {
        let package = file.package_name();
        let service = service_of_package(package).with_context(|| {
            format!(
                "{} is in the package {package:?}, not one shaped origincloud.{{service}}.{{version}} \
                 (such as origincloud.pvs.v1beta1): the generator doesn't know which command group \
                 its methods belong to",
                file.name()
            )
        })?;
        if service != OPERATIONS && file.services().next().is_some() {
            names.push(service.to_owned());
        }
    }
    names.sort();
    names.dedup();
    names
        .into_iter()
        .map(|service| Ok((service.clone(), newest_package(pool, &service)?)))
        .collect()
}

/// The service of a package shaped `origincloud.{service}.{version}`, the
/// service a host label (`[a-z][a-z0-9]*`) and the version one
/// [`version_key`] orders; `None` for any other shape.
fn service_of_package(package: &str) -> Option<&str> {
    let mut parts = package.split('.');
    let (Some("origincloud"), Some(service), Some(version), None) =
        (parts.next(), parts.next(), parts.next(), parts.next())
    else {
        return None;
    };
    let label = service.starts_with(|c: char| c.is_ascii_lowercase())
        && service
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit());
    (label && version_key(version).is_some()).then_some(service)
}

/// Whether each service the SDK has clients of answers at a region's host,
/// from its generated clients: `client.service("pvs", true)` is regional,
/// `client.service("location", false)` isn't.
fn regional_services(sdk: &Path) -> Result<BTreeMap<String, bool>> {
    let call = regex::Regex::new(r#"\.service\(\s*"([a-z0-9-]+)"\s*,\s*(true|false)\s*\)"#)
        .expect("a valid pattern");
    let crates = sdk.join("crates");
    let mut found: BTreeMap<String, bool> = BTreeMap::new();
    let mut files = Vec::new();
    for entry in
        std::fs::read_dir(&crates).with_context(|| format!("reading {}", crates.display()))?
    {
        let generated = entry?.path().join("src").join("generated");
        if generated.is_dir() {
            for file in std::fs::read_dir(&generated)? {
                let path = file?.path();
                if path.extension().is_some_and(|e| e == "rs") {
                    files.push(path);
                }
            }
        }
    }
    files.sort();
    for path in files {
        let text = std::fs::read_to_string(&path)
            .with_context(|| format!("reading {}", path.display()))?;
        for caps in call.captures_iter(&text) {
            let regional = &caps[2] == "true";
            if let Some(before) = found.insert(caps[1].to_owned(), regional) {
                ensure!(
                    before == regional,
                    "the SDK's clients disagree on whether {} is regional",
                    &caps[1]
                );
            }
        }
    }
    ensure!(
        !found.is_empty(),
        "no generated client under {} names its service",
        crates.display()
    );
    Ok(found)
}

/// The newest version of `origincloud.{service}`: a stable version before
/// a beta, a beta before an alpha, and a higher number first.
fn newest_package(pool: &DescriptorPool, service: &str) -> Result<String> {
    let prefix = format!("origincloud.{service}.");
    let mut versions: Vec<(VersionKey, String)> = Vec::new();
    for file in pool.files() {
        let package = file.package_name();
        if let Some(version) = package.strip_prefix(&prefix) {
            let key = version_key(version)
                .with_context(|| format!("the package {package} has no version"))?;
            if !versions.iter().any(|(_, p)| p == package) {
                versions.push((key, package.to_owned()));
            }
        }
    }
    versions.sort();
    versions
        .pop()
        .map(|(_, package)| package)
        .with_context(|| format!("the API has no origincloud.{service} package"))
}

/// Orders versions: (major, stability, minor), stability 0 for alpha, 1 for
/// beta and 2 for stable.
type VersionKey = (u32, u8, u32);

fn version_key(version: &str) -> Option<VersionKey> {
    let rest = version.strip_prefix('v')?;
    let digits = rest.bytes().take_while(u8::is_ascii_digit).count();
    let major = rest[..digits].parse().ok()?;
    let rest = &rest[digits..];
    let (stability, minor) = if rest.is_empty() {
        (2, 0)
    } else if let Some(n) = rest.strip_prefix("beta") {
        (1, n.parse().ok()?)
    } else {
        (0, rest.strip_prefix("alpha")?.parse().ok()?)
    };
    Some((major, stability, minor))
}

/// Whether `method` of `package` has the field `field`, a path from its
/// request such as `volume.size_gib`; whether it has `method`, for an empty
/// `field`.
fn names_a_field(pool: &DescriptorPool, package: &str, method: &str, field: &str) -> bool {
    let Some(method) = pool
        .services()
        .filter(|s| s.package_name() == package)
        .flat_map(|s| s.methods().collect::<Vec<_>>())
        .find(|m| m.name() == method)
    else {
        return false;
    };
    if field.is_empty() {
        return true;
    }
    let mut message = method.input();
    let mut parts = field.split('.').peekable();
    while let Some(part) = parts.next() {
        let Some(f) = message.get_field_by_name(part) else {
            return false;
        };
        if parts.peek().is_some() {
            match f.kind() {
                prost_reflect::Kind::Message(m) => message = m,
                _ => return false,
            }
        }
    }
    true
}

/// The files of `packages` and every file they import, without source info:
/// what the tests need to list the packages' services and methods, and to
/// read their annotations. They are encoded from the pool, which keeps the
/// options' extensions (`google.api.resource` and the like) that
/// `prost_types` drops.
fn descriptor(pool: &DescriptorPool, packages: &[&str]) -> Vec<u8> {
    let mut wanted: Vec<String> = pool
        .files()
        .filter(|f| packages.contains(&f.package_name()))
        .map(|f| f.name().to_owned())
        .collect();
    let mut kept = std::collections::BTreeSet::new();
    while let Some(name) = wanted.pop() {
        if let Some(file) = pool.get_file_by_name(&name) {
            if kept.insert(name) {
                wanted.extend(file.dependencies().map(|d| d.name().to_owned()));
            }
        }
    }
    // Each file after those it imports, in a fixed order.
    let mut out = Vec::new();
    let mut placed = std::collections::BTreeSet::new();
    while placed.len() < kept.len() {
        for name in &kept {
            let file = pool.get_file_by_name(name).expect("a kept file");
            if !placed.contains(name) && file.dependencies().all(|d| placed.contains(d.name())) {
                let encoded = without_field(&file.encode_to_vec(), SOURCE_CODE_INFO);
                // FileDescriptorSet.file, field 1, length-delimited.
                out.push(0x0a);
                prost::encoding::encode_varint(encoded.len() as u64, &mut out);
                out.extend_from_slice(&encoded);
                placed.insert(name.clone());
            }
        }
    }
    out
}

/// `FileDescriptorProto.source_code_info`.
const SOURCE_CODE_INFO: u64 = 9;

/// The encoded message `message` without its field number `field`.
fn without_field(message: &[u8], field: u64) -> Vec<u8> {
    let mut out = Vec::with_capacity(message.len());
    let mut rest = message;
    while !rest.is_empty() {
        let start = rest;
        let key = prost::encoding::decode_varint(&mut rest).expect("a valid descriptor");
        let skip = match key & 7 {
            0 => {
                prost::encoding::decode_varint(&mut rest).expect("a valid descriptor");
                0
            }
            1 => 8,
            2 => prost::encoding::decode_varint(&mut rest).expect("a valid descriptor") as usize,
            5 => 4,
            other => panic!("wire type {other} in a descriptor"),
        };
        rest = &rest[skip..];
        if key >> 3 != field {
            out.extend_from_slice(&start[..start.len() - rest.len()]);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn versions_order_stable_before_beta_before_alpha() {
        let mut keys = ["v1beta1", "v1", "v1alpha2", "v2beta1", "v1beta2"]
            .map(|v| (version_key(v).unwrap(), v));
        keys.sort();
        let order: Vec<&str> = keys.iter().map(|(_, v)| *v).collect();
        assert_eq!(order, ["v1alpha2", "v1beta1", "v1beta2", "v1", "v2beta1"]);
        assert!(version_key("latest").is_none());
    }

    #[test]
    fn a_package_is_origincloud_service_version() {
        assert_eq!(service_of_package("origincloud.pvs.v1beta1"), Some("pvs"));
        assert_eq!(
            service_of_package("origincloud.longrunning.v1"),
            Some("longrunning")
        );
        for bad in [
            "origincloud.pvs",
            "origincloud.pvs.v1beta1.internal",
            "origincloud.pvs.latest",
            "origincloud.Pvs.v1",
            "origincloud.pvs-x.v1",
            "google.pvs.v1",
            "origincloud",
        ] {
            assert_eq!(service_of_package(bad), None, "{bad}");
        }
    }

    #[test]
    fn the_sdk_says_which_services_are_regional() {
        let sdk = std::env::temp_dir().join(format!("cli-gen-sdk-{}", std::process::id()));
        for (krate, text) in [
            ("pvs", "Self { service: client.service(\"pvs\", true) }"),
            (
                "location",
                "service: client.service(\n \"location\", false),",
            ),
        ] {
            let dir = sdk.join("crates").join(krate).join("src").join("generated");
            std::fs::create_dir_all(&dir).unwrap();
            std::fs::write(dir.join("x.rs"), text).unwrap();
        }
        let found = regional_services(&sdk).unwrap();
        std::fs::remove_dir_all(&sdk).unwrap();
        assert_eq!(
            found,
            BTreeMap::from([("location".to_owned(), false), ("pvs".to_owned(), true)])
        );
    }
}
